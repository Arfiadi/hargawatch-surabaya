"""Test fixtures and shared configuration for HargaWatch test suite.

Pytest markers used by this suite
---------------------------------
- ``slow``           : heavy model-training tests; run with ``-m "not slow"`` for a fast loop.
- ``requires_data``  : needs ``data/processed/fact_harga_pasar.csv`` (generated by the pipeline).
- ``integration``    : talks to real infrastructure (Supabase); opt-in with ``RUN_INTEGRATION=1``.

Latency assertions use the ``assert_perf`` fixture and are opt-in with
``HARGAWATCH_PERF_ASSERT=1`` so shared CI machines do not produce flaky failures.

All configuration lives in this file (inside ``tests/``) so the project root stays untouched.
"""

import os
import sys
from pathlib import Path

import pandas as pd
import pytest

# Pastikan root direktori ada di sys.path
BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

HAS_PROCESSED_DATA = (BASE_DIR / "data" / "processed" / "fact_harga_pasar.csv").exists()

MARKERS = {
    "slow": "heavy model-training test; skip with -m 'not slow'",
    "requires_data": "requires data/processed/fact_harga_pasar.csv from the pipeline",
    "integration": "requires real infrastructure; opt in with RUN_INTEGRATION=1",
}


def pytest_configure(config):
    for name, description in MARKERS.items():
        config.addinivalue_line("markers", f"{name}: {description}")


def pytest_collection_modifyitems(config, items):
    """Skip environment-dependent tests explicitly instead of failing or silently hitting live services."""
    skip_no_data = pytest.mark.skip(
        reason="data/processed/fact_harga_pasar.csv not found; run the preprocessing pipeline first"
    )
    skip_integration = pytest.mark.skip(
        reason="integration test disabled; set RUN_INTEGRATION=1 to enable"
    )

    integration_enabled = os.getenv("RUN_INTEGRATION") == "1"
    for item in items:
        if "requires_data" in item.keywords and not HAS_PROCESSED_DATA:
            item.add_marker(skip_no_data)
        if "integration" in item.keywords and not integration_enabled:
            item.add_marker(skip_integration)


@pytest.fixture
def assert_perf():
    """Latency assertions are opt-in so CI on slow/shared machines is not flaky.

    Set ``HARGAWATCH_PERF_ASSERT=1`` to enforce the thresholds locally or in a dedicated
    performance job. Functional assertions in the same tests always run.
    """

    enabled = os.getenv("HARGAWATCH_PERF_ASSERT") == "1"

    def _assert(duration: float, limit_seconds: float, label: str) -> None:
        if enabled:
            assert duration < limit_seconds, f"{label} took {duration:.2f}s (limit {limit_seconds:.1f}s)"

    return _assert


